#!/usr/bin/env bash
#
# wp-visitor-insights installer
#
# Deploys the self-hosted WordPress visitor analytics app and drops the
# collector mu-plugin + per-site dashboard into each WordPress install.
#
# Usage:
#   sudo ./install.sh [options]
#
# Options:
#   --sites FILE        site list (default: ./sites.list, see sites.list.example)
#   --prefix DIR        install directory (default: /opt/wp-visitor-insights)
#   --port N            loopback port for the dashboard app (default: 8095)
#   --db-socket PATH    MySQL socket for admin ops (default: /run/mysqld/mysqld.sock)
#   --run-user USER     PHP-FPM/web user (default: www-data)
#   --no-service        do not install/start the systemd service
#   --tailscale-port N  also expose the dashboard over tailnet HTTPS on port N
#   -h, --help          this help
#
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PREFIX="/opt/wp-visitor-insights"
PORT="8095"
SITES_FILE="$SRC/sites.list"
DB_SOCKET="/run/mysqld/mysqld.sock"
RUN_USER="www-data"
WITH_SERVICE=1
TS_PORT=""
PHP_BIN="$(command -v php || true)"

log()  { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

while [ $# -gt 0 ]; do
  case "$1" in
    --sites) SITES_FILE="$2"; shift 2;;
    --prefix) PREFIX="$2"; shift 2;;
    --port) PORT="$2"; shift 2;;
    --db-socket) DB_SOCKET="$2"; shift 2;;
    --run-user) RUN_USER="$2"; shift 2;;
    --no-service) WITH_SERVICE=0; shift;;
    --tailscale-port) TS_PORT="$2"; shift 2;;
    -h|--help) sed -n '2,25p' "$0"; exit 0;;
    *) die "unknown option: $1";;
  esac
done

[ -n "$PHP_BIN" ] || die "php not found in PATH"
[ -f "$SITES_FILE" ] || die "site list not found: $SITES_FILE (copy sites.list.example)"

mysql_run() { mysql --socket="$DB_SOCKET" "$@"; }

# ---- read site list --------------------------------------------------------
declare -a S_KEYS S_LABELS S_PATHS S_DBS S_PREFIXES
while IFS='|' read -r key label path db prefix; do
  key="$(echo "${key:-}" | xargs)"; [ -z "$key" ] && continue
  case "$key" in \#*) continue;; esac
  label="$(echo "${label:-}" | xargs)"; path="$(echo "${path:-}" | xargs)"
  db="$(echo "${db:-}" | xargs)"; prefix="$(echo "${prefix:-}" | xargs)"
  [ -n "$path" ] || die "site '$key': missing wordpress path"
  [ -d "$path" ] || die "site '$key': path does not exist: $path"
  [ -f "$path/wp-config.php" ] || die "site '$key': no wp-config.php under $path"
  S_KEYS+=("$key"); S_LABELS+=("$label"); S_PATHS+=("$path"); S_DBS+=("$db"); S_PREFIXES+=("${prefix:-wp_}")
done < "$SITES_FILE"
[ "${#S_KEYS[@]}" -gt 0 ] || die "no sites parsed from $SITES_FILE"

# ---- app files -------------------------------------------------------------
log "Installing application to $PREFIX"
mkdir -p "$PREFIX"
for d in lib www bin src docs; do [ -d "$SRC/$d" ] && cp -a "$SRC/$d" "$PREFIX/"; done
[ -f "$SRC/README.md" ] && cp -a "$SRC/README.md" "$PREFIX/"
chmod +x "$PREFIX"/bin/*.sh 2>/dev/null || true

# GeoIP database (not shipped; download one)
mkdir -p "$PREFIX/geoip"
if [ ! -f "$PREFIX/geoip/GeoLite2-Country.mmdb" ]; then
  log "Downloading GeoLite2 country database"
  curl -fsSL --max-time 300 -o "$PREFIX/geoip/GeoLite2-Country.mmdb" \
    "https://raw.githubusercontent.com/P3TERX/GeoLite.mmdb/download/GeoLite2-Country.mmdb" \
    || warn "GeoIP download failed — run bin/geo-update.sh later (country lookups will be empty until then)"
fi

# ---- database user + config ------------------------------------------------
log "Creating read-only database user 'vi_read'"
PW="$(openssl rand -hex 16)"
{
  mysql_run <<SQL
CREATE USER IF NOT EXISTS 'vi_read'@'localhost' IDENTIFIED BY '$PW';
ALTER USER 'vi_read'@'localhost' IDENTIFIED BY '$PW';
CREATE USER IF NOT EXISTS 'vi_read'@'127.0.0.1' IDENTIFIED BY '$PW';
ALTER USER 'vi_read'@'127.0.0.1' IDENTIFIED BY '$PW';
SQL
  for i in "${!S_KEYS[@]}"; do
    mysql_run -e "GRANT SELECT ON \`${S_DBS[$i]}\`.* TO 'vi_read'@'localhost'; GRANT SELECT ON \`${S_DBS[$i]}\`.* TO 'vi_read'@'127.0.0.1';"
  done
  mysql_run -e "FLUSH PRIVILEGES;"
} || die "failed to configure database user (run as root / check --db-socket)"

log "Writing $PREFIX/www/config.php"
{
  echo "<?php"
  echo "/* Generated by install.sh on $(date -Is). Keep mode 640, owner root:$RUN_USER. */"
  echo "return array("
  echo "    'db' => array('host' => '127.0.0.1', 'port' => 3306, 'user' => 'vi_read', 'pass' => '$PW'),"
  echo "    'sites' => array("
  for i in "${!S_KEYS[@]}"; do
    printf "        '%s' => array('label' => '%s', 'db' => '%s', 'prefix' => '%s'),\n" \
      "${S_KEYS[$i]}" "${S_LABELS[$i]}" "${S_DBS[$i]}" "${S_PREFIXES[$i]}"
  done
  echo "    ),"
  echo ");"
} > "$PREFIX/www/config.php"

# ---- permissions -----------------------------------------------------------
chown -R root:"$RUN_USER" "$PREFIX/www"
find "$PREFIX" -type d -exec chmod 755 {} \;
find "$PREFIX" -type f -exec chmod 644 {} \;
chmod 755 "$PREFIX"/bin/*.sh
chown root:"$RUN_USER" "$PREFIX/www/config.php"; chmod 640 "$PREFIX/www/config.php"

# ---- mu-plugins ------------------------------------------------------------
for i in "${!S_KEYS[@]}"; do
  MU="${S_PATHS[$i]}/wp-content/mu-plugins"
  log "Installing collector into ${S_LABELS[$i]} ($MU)"
  mkdir -p "$MU"
  for f in visitor-insights.php visitor-insights-dashboard.php vi-beacon.js; do
    install -o "$RUN_USER" -g "$RUN_USER" -m 644 "$SRC/src/mu-plugin/$f" "$MU/$f"
    # point the mu-plugin at the actual install dir
    sed -i "s#/opt/wp-visitor-insights#$PREFIX#g" "$MU/$f"
  done
done

# ---- systemd service -------------------------------------------------------
if [ "$WITH_SERVICE" -eq 1 ]; then
  log "Installing systemd service (loopback $PORT)"
  cat > /etc/systemd/system/wp-visitor-insights.service <<UNIT
[Unit]
Description=Visitor Insights dashboard (self-hosted WordPress analytics)
After=network-online.target mariadb.service
Wants=network-online.target

[Service]
Type=simple
User=$RUN_USER
Group=$RUN_USER
Environment=VI_APP_DIR=$PREFIX
Environment=VI_PORT=$PORT
ExecStart=$PREFIX/bin/serve.sh
Restart=always
RestartSec=3
NoNewPrivileges=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
UNIT
  systemctl daemon-reload
  systemctl enable --now wp-visitor-insights.service
  sleep 1
  systemctl is-active --quiet wp-visitor-insights.service && log "service active" || warn "service not active — check: journalctl -u wp-visitor-insights"
fi

# ---- tailscale -------------------------------------------------------------
if [ -n "$TS_PORT" ] && command -v tailscale >/dev/null 2>&1; then
  log "Exposing over tailnet HTTPS on :$TS_PORT"
  tailscale serve --bg --https="$TS_PORT" "http://127.0.0.1:$PORT" >/dev/null
fi

# ---- smoke test ------------------------------------------------------------
log "Smoke test"
code=$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$PORT/" || true)
api=$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$PORT/api.php?range=24h" || true)
cfg=$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$PORT/config.php" || true)
echo "   dashboard HTTP $code | api HTTP $api | config.php HTTP $cfg (expect 403)"

log "Done."
echo
echo "Standalone : http://127.0.0.1:$PORT/"
for i in "${!S_KEYS[@]}"; do
  dom=$(echo "${S_LABELS[$i]}" | sed -E 's#^https?://##')
  echo "Per site   : https://$dom/visitor-insights/   (${S_LABELS[$i]}, admins only)"
done
[ -n "$TS_PORT" ] && echo "Tailnet    : https://<your-node>.ts.net:$TS_PORT/"
